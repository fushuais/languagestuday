export function interviewToTopic(item) {
  return {
    id: `interview-${item.id}`,
    interviewId: item.id,
    category: 'interview',
    title: `面接Q${item.id} ${item.q}`,
    titleZh: item.zh,
    emoji: '🎙️',
    keywords: item.keywords,
    expressions: [],
    questions: [item.q],
    model: item.a,
  }
}

export function renderAnswer(text, profile) {
  const p = profile ?? {}
  return String(text)
    .replaceAll('{名前}', `${p.name}（${p.nameKana}）`)
    .replaceAll('{出身}', p.hometown)
    .replaceAll('{年齢}', p.age)
    .replaceAll('{アルバイト}', p.parttime)
    .replaceAll('{住まい}', p.home)
    .replaceAll('{出席率}', p.attendance)
    .replaceAll('{生活費}', p.livingCost)
    .replaceAll('{月給}', p.monthlySalary)
    .replaceAll('{N級}', p.jlptLevel)
    .replaceAll('{目標級}', p.jlptGoal)
    .replaceAll('{兄弟}', p.siblings)
    .replaceAll('{父仕事}', p.fatherJob)
    .replaceAll('{母仕事}', p.motherJob)
    .replaceAll('{時給}', p.hourlyWage || '1100')
    .replaceAll('{時間}', p.workHours || '20')
}
