export const LEVELS = [
  { id: 'basic', label: '基礎', short: '基礎', order: 0 },
  { id: 'mid', label: '発展', short: '中級', order: 1 },
  { id: 'adv', label: '応用', short: '上級', order: 2 },
  { id: 'interview', label: '面接対策', short: '面接', order: 3 },
]

const LEVEL_BY_CATEGORY = {
  intro: 'basic',
  life: 'basic',
  food: 'basic',
  travel: 'mid',
  work: 'mid',
  hobby: 'mid',
  culture: 'adv',
  future: 'adv',
  interview: 'interview',
}

export function topicLevel(category) {
  return LEVEL_BY_CATEGORY[category] ?? 'basic'
}

export function learningPath() {
  return [...CATEGORIES]
    .sort((a, b) => {
      const la = LEVEL_BY_CATEGORY[a.id] ?? 'basic'
      const lb = LEVEL_BY_CATEGORY[b.id] ?? 'basic'
      const oa = LEVELS.find((l) => l.id === la)?.order ?? 0
      const ob = LEVELS.find((l) => l.id === lb)?.order ?? 0
      return oa - ob || CATEGORIES.indexOf(a) - CATEGORIES.indexOf(b)
    })
    .map((c) => c.id)
}
