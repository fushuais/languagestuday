#!/usr/bin/env python3
import re, json, collections, os

SRC = '/tmp/notes.csv'  # 下载自仓库 5mdld/anki-jlpt-decks (eggrolls-JLPT10k-v3.5)
OUT = '/Users/fushuai/Documents/Default Project/nihongo-speaking/public/data'

def clean(s):
    s = re.sub(r'<[^>]+>', '', s or '')
    return s.strip()

rows = []
import sys
if len(sys.argv) > 1:
    SRC = sys.argv[1]
with open(SRC, encoding='utf-8') as f:
    for line in f:
        if line.startswith('#') or not line.strip():
            continue
        rows.append(line.rstrip('\n').split('\t'))

def level_of(deck):
    m = re.search(r'::(\d)-N(\d)', deck)
    return 'N' + m.group(2) if m else None

LV_ORDER = {'N5': 0, 'N4': 1, 'N3': 2, 'N2': 3, 'N1': 4}

seen = {}
for c in rows:
    word_raw = c[3]
    kana = c[6].strip()
    inline = ''
    if '[' in word_raw:
        base = word_raw.split('[')[0].strip()
        m = re.search(r'\[([^\]]*)\]', word_raw)
        if m:
            inline = m.group(1).strip()
        word_raw = base
    word = word_raw.strip()
    if not word or not kana:
        kana = inline
    if kana and re.fullmatch(r'[\sA-Za-z（）()（法）·．?!&.;,\-°0-9″′]+', kana):
        kana = ''
    zh = clean(c[7])
    if not word or not zh:
        continue
    lv = level_of(c[1])
    if lv not in LV_ORDER or LV_ORDER[lv] > 3:  # N5..N2 only
        continue
    exJa = clean(c[12])
    exZh = clean(c[14])
    item = {
        'ja': word,
        'kana': kana,
        'zh': zh,
        'exJa': exJa if (exJa and exZh) else '',
        'exZh': exZh if (exJa and exZh) else '',
    }
    if word in seen:
        if LV_ORDER[lv] < LV_ORDER[seen[word][0]]:
            seen[word] = (lv, item)
    else:
        seen[word] = (lv, item)

items = [(lv, it) for lv, it in seen.values()]
print('unique words N5-N2:', len(items))

by_level = collections.defaultdict(list)
for lv, it in items:
    by_level[lv].append(it)
for lv in ['N5', 'N4', 'N3', 'N2']:
    path = os.path.join(OUT, f'vocab-{lv.lower()}.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(by_level[lv], f, ensure_ascii=False)
    print(f'vocab-{lv.lower()}.json', len(by_level[lv]))

