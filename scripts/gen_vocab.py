def scene_score(w, kws):
    ja, kana, zh = w['ja'], w['kana'], w['zh']
    hay = ja + ' ' + kana + ' ' + zh
    s = 0
    for k in kws:
        if len(k) == 1:
            if k in ja:
                s += 1
        elif k in hay:
            s += len(k) * len(k)
    return s

